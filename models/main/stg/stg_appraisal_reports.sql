-- raw_appraisal_reports は鑑定評価書 1 通を 1 行とし、109 項目を JSON 文字列で
-- 保持している。ここで json_extract により各項目を取り出して構造化する。
-- 標準地番号は「地域名 + 用途区分コード + '-' + 連番」で組み立てる。住宅地
-- (用途区分コード 00) だけは用途区分コードを付けない。mart_land_prices の
-- standard_lot_number と同じ表記になる。
select
    try_cast(json_extract_string(properties, '$."価格時点"') as integer) as year,
    lpad(json_extract_string(properties, '$."標準地番号 市区町村コード 県コード"'), 2, '0') as prefecture_code,
    lpad(json_extract_string(properties, '$."標準地番号 市区町村コード 県コード"'), 2, '0')
        || lpad(json_extract_string(properties, '$."標準地番号 市区町村コード 市区町村コード"'), 3, '0') as city_code,
    _division as use_division_code,
    json_extract_string(properties, '$."標準地番号 地域名"')
        || case when _division = '00' then '' else cast(cast(_division as integer) as varchar) end
        || '-' || json_extract_string(properties, '$."標準地番号 連番"') as standard_lot_number,
    nullif(json_extract_string(properties, '$."標準地番号 地域名"'), '') as district_name,
    nullif(json_extract_string(properties, '$."標準地番号 用途区分"'), '') as use_category,
    try_cast(json_extract_string(properties, '$."標準地番号 連番"') as integer) as branch_number,
    try_cast(json_extract_string(properties, '$."1㎡当たりの価格"') as bigint) as appraised_price,
